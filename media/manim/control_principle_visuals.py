"""Draw recorded one-dimensional Kalman beliefs on a shared position scale.

Intervals express ±one standard deviation, never a guaranteed location range.
Every center, variance and gain comes from the immutable three-event cycle.
No new observations or filtering pass are generated by the display.
"""
import math
from manim import *
from visuals import text,display,TEAL,GOLD,MUTED,RULE,INK
from principle_visuals import recorded_state
BLUE='#90B3FF'

def label(value,x,y,size=18,color=INK,width=7.4,key=None):
    obj=text(str(value),size,color,width=width).move_to([x,y,0])
    if key:obj._motion_key='kalman:'+key
    return obj

def kalman_context(event,run,after=True):
    events=run['trace']['events'];index=int(event['id']);start=index-index%3
    predict,gain,update=events[start:start+3]
    if [e['ruleId'] for e in [predict,gain,update]]!=['kalman-predict','kalman-gain','kalman-update']:
        raise ValueError('Kalman recorded cycle has changed')
    pv=predict['calculation']['values'];gv=gain['calculation']['values'];uv=update['calculation']['values']
    return dict(index=index,phase=index%3,state=recorded_state(event,run,after),previous=pv['旧位置'],previousVariance=pv['旧方差'],predicted=pv['预测位置'],predictedVariance=gv['P预测'],measurement=uv['z'],measurementVariance=gv['R'],gain=gain['calculation']['result'],updated=update['calculation']['result'],updatedVariance=uv['新方差'],after=after)

def kalman_visual(event,run,snapshot,after=True):
    c=kalman_context(event,run,after);phase=c['phase'];out=VGroup()
    low=min(c['previous']-math.sqrt(c['previousVariance']),c['predicted']-math.sqrt(c['predictedVariance']),c['measurement']-math.sqrt(c['measurementVariance']))
    high=max(c['previous']+math.sqrt(c['previousVariance']),c['predicted']+math.sqrt(c['predictedVariance']),c['measurement']+math.sqrt(c['measurementVariance']))
    pad=max(1,(high-low)*.08);low-=pad;high+=pad
    xx=lambda v:-3.1+6.2*(v-low)/(high-low)
    out.add(label('同一把位置尺 · 第'+str(c['index']//3+1)+'次观测',0,1.94,23,GOLD))
    def track(name,mean,var,y,color,key):
        sd=math.sqrt(var);center=xx(mean)
        line=Line([xx(mean-sd),y,0],[xx(mean+sd),y,0],color=color,stroke_width=5);line._motion_key='kalman-interval:'+key
        dot=Dot([center,y,0],radius=.075,color=color);dot._motion_key='kalman-center:'+key
        out.add(line,dot,label(f'{name} {display(mean)} · 方差 {display(var)}',0,y+.22,17,color,key=key))
    if phase==0:
        track('上次估计',c['previous'],c['previousVariance'],1.10,MUTED,'old')
        track('本步预测',c['predicted'],c['predictedVariance'],.35,TEAL,'predicted')
        out.add(Arrow([xx(c['previous']),.83,0],[xx(c['predicted']),.59,0],buff=.02,color=TEAL,stroke_width=2))
        out.add(label('位置前进0.45；过程噪声让方差从 '+display(c['previousVariance'])+' 增至 '+display(c['predictedVariance']),0,-.45,19,INK))
    else:
        track('预测',c['predicted'],c['predictedVariance'],1.10,TEAL,'predicted')
        track('本次测量',c['measurement'],c['measurementVariance'],.35,BLUE,'measurement')
        if phase==2:
            if after:
                track('融合结果',c['updated'],c['updatedVariance'],-.40,GOLD,'updated')
            else:out.add(label('待更新：从预测向测量靠近一部分',0,-.35,19,GOLD))
    axisY=-.88
    out.add(Line([-3.1,axisY,0],[3.1,axisY,0],color=RULE,stroke_width=1))
    for i in range(5):
        value=low+(high-low)*i/4;x=xx(value)
        out.add(Line([x,axisY-.04,0],[x,axisY+.04,0],color=MUTED,stroke_width=1),label(f'{value:.1f}',x,axisY-.18,14,MUTED,.65))
    if phase==1:
        left=-3.1;width=6.2;k=c['gain']
        for x,w,color,key in [(left,width*(1-k),TEAL,'old-weight'),(left+width*(1-k),width*k,BLUE,'new-weight')]:
            bar=Rectangle(width=max(.001,w),height=.22,fill_color=color,fill_opacity=.9,stroke_width=0).move_to([x+w/2,-1.45,0]);bar._motion_key='kalman:'+key;out.add(bar)
        out.add(label(f'信预测 {(1-k)*100:.1f}%   +   信测量 {k*100:.1f}%',0,-1.76,18,INK))
    elif phase==2:
        out.add(label('预测 + 权重 × (测量 − 预测)',0,-1.4,19,INK),label('权重 '+display(c['gain'])+'：只吸收测量差的一部分',0,-1.72,18,GOLD))
    else:out.add(label('这里展示本步推导量；状态是否写入见画面下方',0,-1.55,17,MUTED))
    out.add(label('横线表示中心 ±1 个标准差；不是保证范围',0,-2.08,16,MUTED))
    if phase in {0,1}:out._projection_phase='本步操作数与推导量并列；估计位置尚未融合'
    return out

def control_principle_visual(event,run,snapshot,after=True):
    if run['trace']['algorithmId']=='kalman':return kalman_visual(event,run,snapshot,after)
    return None
