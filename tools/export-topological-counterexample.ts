import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
import {runners} from '../src/algorithms/core';
import {replayTrace,teachingJSON} from '../src/engine/teaching';
import {normalizeInput,normalizeParams} from '../src/engine/validation';
import {byId} from '../src/content/catalog';

const id='topological';
const baseline=JSON.parse(await readFile(`media/exports/${id}.json`,'utf8'));
const input={};
const params={nodes:3,density:0,cycle:'yes'};
const seed=baseline.lesson.teachingCase.seed;
const run=await runners[id](input,params,seed);
const browserRun=await runners[id](normalizeInput(input),normalizeParams(byId[id],params),seed);
assert.equal(teachingJSON(run.trace),teachingJSON(browserRun.trace));
assert.ok(run.trace?.complete);
assert.deepEqual(replayTrace(run.trace!),run.trace!.finalState);
assert.deepEqual(run.trace!.initialState.degree,[1,1,1]);
assert.deepEqual(run.trace!.initialState.ready,[]);
assert.deepEqual(run.trace!.finalState.done,[]);
assert.equal(run.trace!.finalState.possible,false);
assert.deepEqual(run.trace!.events.map(e=>e.phase),['initialize','stop']);
const edges=run.frames[0].scene.edges!.map(e=>`${e.from}->${e.to}`);
assert.deepEqual(edges,['0->1','1->2','2->0']);
const traceHash=createHash('sha256').update(teachingJSON(run.trace)).digest('hex');
const payload={schemaVersion:1,algorithm:{...baseline.algorithm,subtitle:'三任务循环：A → B → C → A'},lesson:{...baseline.lesson,teachingCase:{input,params,seed}},run,traceHash};
await writeFile(`media/exports/${id}-review-counterexample.json`,teachingJSON(payload,2));
console.log(JSON.stringify({id,events:run.trace!.events.length,traceHash,checks:'directed 3-cycle, all indegrees 1, empty ready/done, full trace replay, browser normalization identical'}));
