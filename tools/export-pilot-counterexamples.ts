import {writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {runners} from '../src/algorithms/core';
import {runners as worldRunners} from '../src/algorithms/world';
import {lessonById} from '../src/content/lessons';
import {replayTrace,teachingJSON} from '../src/engine/teaching';
const lesson=lessonById.bfs;
const input={...lesson.teachingCase.input,walls:[2,7,12,17,22]};
const run=await runners.bfs(input,lesson.teachingCase.params,lesson.teachingCase.seed);
assert.deepEqual(replayTrace(run.trace!),run.trace!.finalState);
assert.equal((run.trace!.finalState.route as unknown[]).length,0);
assert.equal(run.trace!.finalState.found,false);
const traceHash=createHash('sha256').update(teachingJSON(run.trace)).digest('hex');
await writeFile('media/exports/bfs-counterexample.json',teachingJSON({schemaVersion:1,algorithm:{id:'bfs',name:'广度优先搜索',subtitle:'障碍隔断反例'},lesson:{...lesson,teachingCase:{...lesson.teachingCase,input}},run,traceHash},2));
console.log(JSON.stringify({events:run.trace!.events.length,metrics:run.metrics,traceHash}));
const pidLesson=lessonById.pid;
const pidParams={...pidLesson.teachingCase.params,gain:4,damping:0};
const pidRun=await worldRunners.pid(pidLesson.teachingCase.input,pidParams,pidLesson.teachingCase.seed);
assert.deepEqual(replayTrace(pidRun.trace!),pidRun.trace!.finalState);
const pidHash=createHash('sha256').update(teachingJSON(pidRun.trace)).digest('hex');
assert.ok(Number(pidRun.metrics['最大超调'])>15);
await writeFile('media/exports/pid-counterexample.json',teachingJSON({schemaVersion:1,algorithm:{id:'pid',name:'PID控制',subtitle:'提高比例增益、取消微分反馈'},lesson:{...pidLesson,teachingCase:{...pidLesson.teachingCase,params:pidParams}},run:pidRun,traceHash:pidHash},2));
console.log(JSON.stringify({id:'pid',metrics:pidRun.metrics,traceHash:pidHash}));
